// Helper to generate realistic polygon bounds around center coordinates
function createWardBounds(lat, lng, deltaLat = 0.007, deltaLng = 0.009, angleShift = 0) {
  const dLat = deltaLat * 0.5;
  const dLng = deltaLng * 0.5;
  return [
    [lat + dLat + angleShift, lng - dLng],
    [lat + dLat * 0.9, lng + dLng + angleShift],
    [lat - dLat - angleShift, lng + dLng * 0.9],
    [lat - dLat * 0.9, lng - dLng - angleShift]
  ];
}

